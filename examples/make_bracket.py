"""Generate examples/bracket.fem: a shell L-bracket with a bolted base and a loaded tab.

A small, fully synthetic deck (no confidential model data) used for the README images
and as an end-to-end test of the parser.
"""
from pathlib import Path

import numpy as np

nx, ny, nz = 24, 12, 16  # elements along length, base width, wall height
L, W, H = 240.0, 120.0, 160.0  # mm
nodes, shells = {}, []
nid = 1


def grid(x, y, z):
    global nid
    nodes[nid] = (x, y, z)
    nid += 1
    return nid - 1


base = [[grid(i * L / nx, j * W / ny, 0.0) for j in range(ny + 1)] for i in range(nx + 1)]
wall = [[base[i][ny] if k == 0 else grid(i * L / nx, W, k * H / nz) for k in range(nz + 1)] for i in range(nx + 1)]
for i in range(nx):
    for j in range(ny):
        shells.append((base[i][j], base[i + 1][j], base[i + 1][j + 1], base[i][j + 1]))
    for k in range(nz):
        shells.append((wall[i][k], wall[i + 1][k], wall[i + 1][k + 1], wall[i][k + 1]))

load_master = grid(L / 2, W + 60.0, H * 0.75)  # loading point in front of the wall
rbe_load = [wall[i][k] for i in range(nx // 2 - 2, nx // 2 + 3) for k in range(nz // 2, nz)]
bolts = []
for (bi, bj) in [(3, 3), (nx - 3, 3), (3, ny - 4), (nx - 3, ny - 4)]:
    centre = grid(bi * L / nx, bj * W / ny, -20.0)
    bolts.append((centre, [base[bi + a][bj + b] for a in (-1, 0, 1) for b in (-1, 0, 1)]))


def real(value: float) -> str:
    """Nastran real field: always contains a decimal point and fits in 8 characters."""
    text = f"{value:.4g}"
    return text if ("." in text or "e" in text) else text + "."


def small(*fields):
    out = f"{fields[0]:<8}"
    for f in fields[1:]:
        out += f"{real(f) if isinstance(f, float) else f:>8}"
    return out


lines = [
    "$ Synthetic L-bracket generated by examples/make_bracket.py (units: mm, N)",
    "SUBCASE 1", "  LABEL = pull_out", "  ANALYSIS STATICS", "  SPC = 1", "  LOAD = 10",
    "SUBCASE 2", "  LABEL = side_load_combined", "  ANALYSIS STATICS", "  SPC = 1", "  LOAD = 20",
    "BEGIN BULK",
]
lines += [small("GRID", n, "", float(x), float(y), float(z)) for n, (x, y, z) in nodes.items()]
lines += [small("CQUAD4", e + 1, 1, *s) for e, s in enumerate(shells)]


def rbe2(eid, master, deps):
    first, rest = deps[:5], deps[5:]
    out = [small("RBE2", eid, master, "123456", *first)]
    while rest:
        out.append(small("+", *rest[:8]))
        rest = rest[8:]
    return out


eid = 10000
lines += rbe2(eid, load_master, rbe_load)
for centre, deps in bolts:
    eid += 1
    lines += rbe2(eid, centre, deps)
    lines.append(small("SPC", 1, centre, "123456", 0.0))
lines += [
    small("FORCE", 11, load_master, 0, 1.0, 0.0, 1500.0, 0.0),
    small("FORCE", 12, load_master, 0, 1.0, 900.0, 0.0, 0.0),
    small("FORCE", 13, load_master, 0, 1.0, 0.0, 0.0, -600.0),
    small("LOAD", 10, 1.0, 1.0, 11),
    small("LOAD", 20, 1.0, 1.0, 12, 1.0, 13),
    "ENDDATA",
]
Path(__file__).with_name("bracket.fem").write_text("\n".join(lines) + "\n")
print(f"wrote bracket.fem: {len(nodes)} nodes, {len(shells)} shells")
